function __($key, $data = []) {
    global $translations, $lang;
    $text = $translations[$lang][$key] ?? $translations['en'][$key] ?? $key;
    
    if (!empty($data)) {
        foreach ($data as $k => $v) {
            $text = str_replace('{' . $k . '}', $v, $text);
        }
    }
    return $text;
}

function translate_msg($msg) {
    if (strpos($msg, '::') !== false) {
        $parts = explode('::', $msg);
        $key = $parts[0];
        $payload = json_decode($parts[1] ?? '{}', true);
        return __($key, $payload);
    }
    return $msg;
}
